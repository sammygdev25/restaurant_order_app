#!/bin/bash
# Push Restaurant Order App to GitHub
# Usage: ./git_push.sh <your-github-repo-url>

set -e

REPO_URL=$1

if [ -z "$REPO_URL" ]; then
    echo "Usage: ./git_push.sh https://github.com/username/repo.git"
    exit 1
fi

echo "Initializing git repository..."
git init
git add -A
git commit -m "Initial commit: Restaurant Order App — generated by Shikshya"

echo "Adding remote..."
git remote add origin "$REPO_URL"

echo "Pushing to GitHub..."
git branch -M main
git push -u origin main

echo ""
echo "Done! Your project is live at: $REPO_URL"
